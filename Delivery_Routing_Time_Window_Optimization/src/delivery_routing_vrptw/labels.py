_ALIASES = {"pt": "pt", "pt-br": "pt", "pt_br": "pt", "en": "en", "en-us": "en", "en_us": "en"}


def get_labels(language: str) -> dict[str, dict[str, str]]:
    """Return the label dictionary for a language.

    Parameters
    ----------
    language : str
        ``"pt"``, ``"pt-br"``, ``"en"`` or ``"en-us"`` (case-insensitive; ``_`` also accepted).

    Returns
    -------
    dict
        Nested mapping ``group -> key -> text``.
    """
    key = _ALIASES.get(language.strip().lower())
    if key is None:
        raise ValueError(f"unsupported language: {language!r}")
    return LABELS[key]
